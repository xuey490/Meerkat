// TestRenderValue 覆盖字面量渲染：重点是整型不能再出现 MySQL 风格的宽度
// （旧实现把 bigint 渲染成 bigint(64) 导致导入时语法报错）。
func TestRenderValue(t *testing.T) {
	cases := []struct {
		name     string
		typeName string
		value    any
		want     string
	}{
		{"bigint 整数不带宽度", "bigint", int64(64), "64"},
		{"integer 整数不带宽度", "integer", int64(32), "32"},
		{"smallint", "smallint", int64(16), "16"},
		{"numeric 文本原样输出", "numeric", []byte("1234.5678"), "1234.5678"},
		{"numeric 非法文本报错", "numeric", []byte("abc"), ""},
		{"布尔", "boolean", true, "true"},
		{"整数列里的布尔转 1", "integer", true, "1"},
		{"NULL", "text", nil, "NULL"},
		{"字符串单引号翻倍", "character varying(64)", "it's ok", "'it''s ok'"},
		{"中文与反斜杠", "text", `路径 D:\监控\a`, `'路径 D:\监控\a'`},
		{"jsonb 带类型转换", "jsonb", []byte(`{"a":1}`), `'{"a":1}'::jsonb`},
		{"bytea 十六进制", "bytea", []byte{0xde, 0xad}, `'\xdead'::bytea`},
		{"带时区时间戳保留偏移", "timestamp with time zone",
			time.Date(2026, 10, 13, 10, 20, 30, 123456000, time.FixedZone("CST", 8*3600)),
			"'2026-10-13 10:20:30.123456+08:00'"},
		{"不带时区时间戳", "timestamp without time zone",
			time.Date(2026, 10, 13, 10, 20, 30, 123456000, time.UTC),
			"'2026-10-13 10:20:30.123456'"},
		{"日期", "date", time.Date(2026, 10, 13, 0, 0, 0, 0, time.UTC), "'2026-10-13'"},
	}
	for _, item := range cases {
		t.Run(item.name, func(t *testing.T) {
			got, err := renderValue(item.typeName, item.value)
			if item.want == "" {
				if err == nil {
					t.Fatalf("期望报错，实际得到 %q", got)
				}
				return
			}
			if err != nil {
				t.Fatalf("渲染失败: %v", err)
			}
			if got != item.want {
				t.Fatalf("渲染结果不符\n期望: %s\n实际: %s", item.want, got)
			}
		})
	}
}

// TestQuoteStringLiteral 覆盖字符串字面量转义，含必须走 E 前缀转义的 NUL 场景。
func TestQuoteStringLiteral(t *testing.T) {
	if got := quoteStringLiteral("it's"); got != "'it''s'" {
		t.Fatalf("单引号转义不符: %s", got)
	}
	if got := quoteStringLiteral("a\x00b"); got != `E'a\000b'` {
		t.Fatalf("NUL 转义不符: %s", got)
	}
}

// TestDumpRoundTrip 验证「导出的 SQL 能被另一个 schema 完整导入」。
//
// 这是本包存在的理由：旧实现导出的文件在导入时必然失败（bigint(64) 语法错、
// 缺序列、缺索引、缺自增）。用例把源 schema 导出后，把 DDL 里的 schema 名替换成
// 另一个 schema 并执行，然后逐表比对内容摘要、对象数量与自增能力。
func TestDumpRoundTrip(t *testing.T) {
	source := pgtest.Open(t)
	sourceSchema := currentSchema(t, source)

	statements := []string{
		// identity 主键（旧实现会丢掉自增能力）、serial 序列、普通索引、唯一索引
		`CREATE TABLE alert_probe (
			id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			name character varying(64) NOT NULL,
			score numeric(10,2),
			payload jsonb,
			raw bytea,
			ratio double precision,
			enabled boolean,
			created_at timestamp with time zone,
			local_at timestamp without time zone,
			note text
		)`,
		`CREATE UNIQUE INDEX ux_alert_probe_name ON alert_probe (name)`,
		`CREATE INDEX ix_alert_probe_created_at ON alert_probe (created_at)`,
		`CREATE SEQUENCE probe_seq AS bigint START WITH 100 INCREMENT BY 2`,
	}
	for _, statement := range statements {
		if err := source.Exec(statement).Error; err != nil {
			t.Fatalf("准备源表失败: %v\nSQL: %s", err, statement)
		}
	}

	created := time.Date(2026, 10, 13, 9, 30, 0, 123456000, time.FixedZone("CST", 8*3600))
	insert := `INSERT INTO alert_probe (name, score, payload, raw, ratio, enabled, created_at, local_at, note)
		VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)`
	rows := [][]any{
		{"含'引号", "12.34", `{"k":"v"}`, []byte{0x00, 0xff}, 1.5, true, created, created, "多行\n文本\\反斜杠"},
		{"空值行", nil, nil, nil, nil, nil, nil, nil, nil},
	}
	for _, row := range rows {
		if err := source.Exec(insert, row...).Error; err != nil {
			t.Fatalf("写入源数据失败: %v", err)
		}
	}
	// 显式指定 id 的插入：模拟「导入时带上原始主键」，序列不会自动前进。
	if err := source.Exec(`INSERT INTO alert_probe (id, name) VALUES (900, '显式主键')`).Error; err != nil {
		t.Fatalf("写入显式主键失败: %v", err)
	}

	sqlDB, err := source.DB()
	if err != nil {
		t.Fatalf("获取底层连接失败: %v", err)
	}
	var buffer bytes.Buffer
	stats, err := Dump(context.Background(), sqlDB, &buffer, Options{
		Schemas:     []string{sourceSchema},
		IncludeData: true,
		Database:    "pgdump_test",
	})
	if err != nil {
		t.Fatalf("导出失败: %v", err)
	}
	dump := buffer.String()
	if stats.Tables != 1 || stats.Rows != 3 {
		t.Fatalf("导出统计不符: %+v", stats)
	}
	// 旧实现的典型故障：类型被写成 MySQL 风格宽度。
	if strings.Contains(dump, "integer(32)") || strings.Contains(dump, "bigint(64)") {
		t.Fatalf("导出内容里出现了 MySQL 风格的类型宽度:\n%s", dump)
	}
	if !strings.Contains(dump, "GENERATED BY DEFAULT AS IDENTITY") {
		t.Fatalf("导出内容缺少 identity 还原语句:\n%s", dump)
	}
	if !strings.Contains(dump, "CREATE INDEX ix_alert_probe_created_at") ||
		!strings.Contains(dump, "CREATE UNIQUE INDEX ux_alert_probe_name") {
		t.Fatalf("导出内容缺少索引:\n%s", dump)
	}
	if !strings.Contains(dump, "setval") {
		t.Fatalf("导出内容缺少 setval:\n%s", dump)
	}

	target := pgtest.Open(t)
	targetSchema := currentSchema(t, target)
	// 注意：本包自己写的 DDL 用双引号包住标识符，而 pg_get_indexdef / pg_get_constraintdef
	// 的原文在「不加引号也合法」时是裸标识符（如 test_123_1.alert_probe），
	// 因此这里必须替换不带引号的形式，否则索引会被建到源 schema 上。
	restored := strings.ReplaceAll(dump, sourceSchema, targetSchema)
	if err := target.Exec(restored).Error; err != nil {
		t.Fatalf("导入备份失败: %v\n--- SQL 片段 ---\n%s", err, snippet(restored, err))
	}

	// 1. 数据内容逐表比对（整行文本的 md5，与列顺序无关的差异也会被发现）。
	if got, want := rowDigest(t, target, targetSchema, "alert_probe"), rowDigest(t, source, sourceSchema, "alert_probe"); got != want {
		t.Fatalf("导入后数据不一致\n源: %s\n目标: %s", want, got)
	}
	// 2. 对象数量比对：索引与序列一个都不能少。
	// 主键索引 + 唯一索引 + 普通索引 = 3，少一个都说明索引没恢复全。
	assertCount(t, target, `
		SELECT count(*) FROM pg_indexes WHERE schemaname = ? AND tablename = 'alert_probe'`,
		targetSchema, 3, "目标表索引数")
	assertCount(t, target, `
		SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
		WHERE c.relkind = 'S' AND n.nspname = ?`, targetSchema, 2, "目标 schema 序列数")

	// 3. 自增能力：显式主键 900 已存在，序列必须被推进到 900 之后。
	//    这里用全限定表名，避免依赖会话 search_path。
	var nextID int64
	insertBack := fmt.Sprintf(`INSERT INTO %s (name) VALUES ('自增验证') RETURNING id`,
		qualified(targetSchema, "alert_probe"))
	if err := target.Raw(insertBack).Scan(&nextID).Error; err != nil {
		t.Fatalf("导入后新增数据失败（序列未校正）: %v", err)
	}
	if nextID <= 900 {
		t.Fatalf("导入后自增主键未推进，得到 %d", nextID)
	}
}

// currentSchema 读取会话当前 schema。
//
// 参数 Parameters:
//   - t (*testing.T): 当前测试。
//   - db (gorm.DB): 测试会话。
//
// 返回 Returns:
//   - schema (string): schema 名。
func currentSchema(t *testing.T, db *gorm.DB) string {
	t.Helper()
	var schema string
	if err := db.Raw("SELECT current_schema()").Scan(&schema).Error; err != nil {
		t.Fatalf("读取当前 schema 失败: %v", err)
	}
	return schema
}

// rowDigest 计算一张表全部行的内容摘要。
//
// 参数 Parameters:
//   - t (*testing.T): 当前测试。
//   - db (gorm.DB): 目标会话。
//   - schema (string): 表所属 schema。
//   - table (string): 表名。
//
// 返回 Returns:
//   - digest (string): md5 摘要。
func rowDigest(t *testing.T, db *gorm.DB, schema, table string) string {
	t.Helper()
	query := fmt.Sprintf(
		`SELECT COALESCE(md5(string_agg(t::text, '|' ORDER BY t::text)), '') FROM %s.%s t`,
		quoteIdent(schema), quoteIdent(table))
	var digest string
	if err := db.Raw(query).Scan(&digest).Error; err != nil {
		t.Fatalf("计算摘要失败: %v", err)
	}
	return digest
}

// assertCount 断言查询结果等于期望值。
//
// 参数 Parameters:
//   - t (*testing.T): 当前测试。
//   - db (*gorm.DB): 目标会话。
//   - query (string): 返回单值的 SQL。
//   - arg (any): 查询参数。
//   - want (int): 期望值。
//   - label (string): 断言名称。
func assertCount(t *testing.T, db *gorm.DB, query string, arg any, want int, label string) {
	t.Helper()
	var got int
	if err := db.Raw(query, arg).Scan(&got).Error; err != nil {
		t.Fatalf("%s 查询失败: %v", label, err)
	}
	if got != want {
		t.Fatalf("%s 不符：期望 %d，实际 %d", label, want, got)
	}
}

// snippet 在导入失败时截取可能出错的片段，便于定位是哪条语句出的问题。
//
// 索引、约束与 setval 都在文件尾部，因此默认给尾部；错误提到 INSERT 时给数据段。
//
// 参数 Parameters:
//   - sql (string): 完整脚本。
//   - err (error): 导入错误。
//
// 返回 Returns:
//   - text (string): 出错片段。
func snippet(sql string, err error) string {
	if strings.Contains(err.Error(), "INSERT") {
		if index := strings.Index(sql, "INSERT INTO"); index >= 0 {
			end := index + 600
			if end > len(sql) {
				end = len(sql)
			}
			return sql[index:end]
		}
	}
	if len(sql) > 1500 {
		return "...(已省略前文)...\n" + sql[len(sql)-1500:]
	}
	return sql
}
